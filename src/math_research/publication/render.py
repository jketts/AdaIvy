#: ADR-0058's derived headline vocabulary, frozen. Every phrase a composed title
#: can carry is in this module. The only manuscript strings that reach the
#: displayed title are ``title_stem`` -- screened against ``RESOLUTION_LEXICON``
#: at load time -- and a subject label mechanically derived from a record
#: identifier and screened against the same lexicon here. There is no field whose
#: value selects a qualifier, and no value that removes one.
RESOLUTION_KIND_PHRASES = {"refutation": "Counterexample to", "proof": "Proof of"}

#: The hedge a reader needs when the records do not close the question. It is
#: added unless *every* input is at its strongest, so the default is hedged.
CANDIDATE_PREFIX = "Candidate "

#: Weakest first is the direction that matters: the qualifier is computed from the
#: weakest claim in the document, never from the best one.
SCOPE_WEAKNESS_ORDER = (
    "unconditional", "convention_relative", "contested_unevaluated", "no_reading_refutes",
)
SCOPE_QUALIFIERS = {
    "unconditional": None,
    "convention_relative": "convention-relative",
    "contested_unevaluated": "some enumerated reading was never evaluated",
    "no_reading_refutes": "no enumerated reading refutes",
}
EVIDENCE_CLASS_QUALIFIERS = {
    "kernel_checked_theorem": None,
    "exact_certificate_proposition": None,
    "convention_relative_proposition": None,
    "proposal": "unresolved on these records",
}
#: ADR-0055 report classifications, mapped to reader-facing words. Only
#: ``no_prior_art_found_under_protocol`` clears the qualifier, and it clears it
#: because a bounded search was actually run and recorded.
PRIOR_ART_QUALIFIERS = {
    "no_prior_art_found_under_protocol": None,
    "prior_art_search_inconclusive": "prior-art search inconclusive",
    "reported_prior_resolution": "a prior resolution is reported",
    "independent_verification": "independent verification of a prior result",
    "extension_of_prior_result": "extension of a prior result",
    "related_to_prior_result": "related to a prior result",
    "prior_art_relationship_unresolved": "prior art relationship unresolved",
}
#: The absent-record case, which must read as weaker than every recorded one.
PRIOR_ART_UNASSESSED = "prior art not assessed"
OBLIGATION_TAG_WORDS = {"novelty": "novelty", "prior_art": "prior-art"}
#: Record-kind prefixes dropped when a subject identifier becomes a reader-facing
#: label. Anything else is kept, so an unrecognised namespace stays visible.
SUBJECT_ID_PREFIXES = frozenset({"problem", "conjecture", "question", "subject", "target"})
#: ADR-0060. "source-faithful" is never in this table: it is earned only when
#: every reading is verbatim-confirmed, and then it is still not said here.
READING_FIDELITY_WORDS = {
    "verbatim_confirmed": "source-verbatim reading",
    "transcribed": "source-transcribed reading",
    "asserted": "source-asserted reading",
}
ENUMERATION_LIMIT_SENTENCE = (
    "A derived scope of unconditional means unconditional over the readings this "
    "record enumerates, never over every reading that exists: the enumeration is "
    "author-supplied, and a contested term nobody recorded is invisible to this "
    "machinery. Scope is also a truth-conditional axis and not a priority axis; "
    "whether an earlier candidate pre-empts a result is a prior-art question, "
    "recorded in the replay table and the prior-art classification."
)


def subject_label(subject_id: str) -> str:
    """A reader-facing name for a subject identifier, derived mechanically.

    ``problem.graffiti-322`` becomes ``Graffiti 322``. The transformation is a
    function of the identifier alone, and the result is screened by
    :func:`compose_headline` against the resolution lexicon, because a subject id
    is the one manuscript string the composed title still quotes.
    """

    parts = [part for part in str(subject_id).split(".") if part]
    if len(parts) > 1 and parts[0] in SUBJECT_ID_PREFIXES:
        parts = parts[1:]
    words = [word for word in re.split(r"[-_.]+", ".".join(parts)) if word]
    label = " ".join(
        word if word[:1].isdigit() else word[:1].upper() + word[1:] for word in words
    )
    return label or str(subject_id)


@dataclass(frozen=True, slots=True)
class Headline:
    """The composed displayed title, and the records that composed it."""

    title_stem: str
    resolution_phrase: str
    qualifiers: tuple[str, ...]
    displayed_title: str
    record_refs: tuple[str, ...]
    derivation: tuple[str, ...]


def compose_headline(
    manuscript: Manuscript, classifications: tuple[EvidenceClassification, ...]
) -> Headline:
    """Compose the displayed title from records. No field selects the qualifier.

    The qualifier is lost only when every input is at its strongest: every
    resolution-typed claim sweeps its readings, no claim sits at ``proposal``, a
    prior-art record says a bounded search found nothing, and no obligation
    tagged ``novelty`` or ``prior_art`` is open. Each of those is a record, and a
    missing record is the weak case rather than the silent one.
    """

    stem = str(manuscript.value["title_stem"])
    resolution_claims = manuscript.resolution_claim_ids()
    if not resolution_claims:
        # Nothing claims to resolve anything, so there is nothing to qualify. The
        # stem itself is still refused at load time if it says otherwise.
        return Headline(
            title_stem=stem, resolution_phrase="", qualifiers=(), displayed_title=stem,
            record_refs=(manuscript.manuscript_id,),
            derivation=("no claim carries a resolution_target, so no resolution is claimed",),
        )

    classes = {item.claim_id: item.evidence_class for item in classifications}
    refs: list[str] = [manuscript.manuscript_id]
    derivation: list[str] = []

    scopes: list[str] = []
    phrases: list[str] = []
    weakest_class = "kernel_checked_theorem"
    for claim_id in resolution_claims:
        claim = manuscript.claims[claim_id]
        target = claim["resolution_target"]
        kind = str(target["kind"])
        label = subject_label(str(target["subject_id"]))
        hits = lexicon_hits(label, RESOLUTION_LEXICON)
        if hits:
            raise PublicationValidationError(
                "resolution_subject_label_asserts_resolution",
                f"claim {claim_id} names subject {target['subject_id']!r}, which reads as "
                f"{list(hits)} in the composed title; the derived qualifier decides how "
                "strong a headline is, and a record identifier may not pre-empt it",
            )
        phrase = RESOLUTION_KIND_PHRASES.get(kind)
        if phrase is None:
            raise PublicationValidationError(
                "resolution_target_kind_unrenderable",
                f"claim {claim_id} resolves its target by {kind!r}, which this projection "
                "has no derived phrase for; an unrenderable kind is a refusal, never a "
                "headline the reader has to guess at",
            )
        phrases.append(f"{phrase} {label}")
        refs.append(claim_id)
        matrix = manuscript.verdict_matrix_for(claim_id)
        if matrix is not None:
            refs.extend([matrix.matrix_id, matrix.convention_id])
        scope = manuscript.derived_scope(claim_id)
        if scope is not None:
            scopes.append(scope)
        # A resolution-typed claim that reaches no section block contributes no
        # classification. It counts as the weakest class rather than the
        # strongest: an undisplayed claim must not buy the headline a rung.
        observed = classes.get(claim_id, EVIDENCE_CLASSES[-1])
        if EVIDENCE_CLASSES.index(observed) > EVIDENCE_CLASSES.index(weakest_class):
            weakest_class = observed

    weakest_scope = (
        max(scopes, key=SCOPE_WEAKNESS_ORDER.index) if scopes else "contested_unevaluated"
    )
    derivation.append(f"weakest derived scope across resolution claims: {weakest_scope}")
    derivation.append(f"weakest evidence class across resolution claims: {weakest_class}")

    qualifiers: list[str] = []
    scope_qualifier = SCOPE_QUALIFIERS[weakest_scope]
    if scope_qualifier:
        qualifiers.append(scope_qualifier)
    class_qualifier = EVIDENCE_CLASS_QUALIFIERS[weakest_class]
    if class_qualifier:
        qualifiers.append(class_qualifier)

    recheck = manuscript.prior_art_recheck()
    if recheck is None:
        qualifiers.append(PRIOR_ART_UNASSESSED)
        derivation.append("prior_art_engagement is null")
    else:
        classification = recheck.classification()
        refs.append(recheck.recheck_id)
        derivation.append(
            f"prior-art classification {classification.report_classification} from "
            f"{recheck.recheck_id}"
        )
        prior_qualifier = PRIOR_ART_QUALIFIERS[classification.report_classification]
        if prior_qualifier:
            qualifiers.append(prior_qualifier)

    open_tags = manuscript.open_obligation_tags() & set(OBLIGATION_TAG_WORDS)
    if open_tags:
        words = " and ".join(OBLIGATION_TAG_WORDS[tag] for tag in sorted(open_tags))
        qualifiers.append(f"open {words} obligations")
        for obligation_id, obligation in sorted(manuscript.obligations.items()):
            if obligation["status"] in {"open", "blocked"} and set(obligation["tags"]) & open_tags:
                refs.append(obligation_id)
        derivation.append(
            "open obligations tagged " + ", ".join(sorted(open_tags))
        )

    hedged = bool(qualifiers) or weakest_class != "kernel_checked_theorem"
    prefix = CANDIDATE_PREFIX if hedged else ""
    resolution_phrase = prefix + " and ".join(dict.fromkeys(phrases))
    displayed = stem + ": " + resolution_phrase
    if qualifiers:
        displayed += " (" + "; ".join(qualifiers) + ")"
    return Headline(
        title_stem=stem, resolution_phrase=resolution_phrase, qualifiers=tuple(qualifiers),
        displayed_title=displayed, record_refs=tuple(dict.fromkeys(refs)),
        derivation=tuple(derivation),
    )


