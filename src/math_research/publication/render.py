"""Deterministic projection of a manuscript record set into ``paper.tex``.

Three properties are mechanical rather than conventional.

**Ledger closure.** ``paper.tex`` is exactly the frozen template plus the
concatenation of the ledger's blocks. Every block carries at least one record
reference, so a block cannot reach the document without appearing in the ledger,
and cannot appear in the ledger without a reference. ``verify_ledger_closure``
recomputes the concatenation and compares bytes.

**Computed environments.** No manuscript field names an environment. Every claim
is classified by :mod:`evidence`, and every classification is reported in the
document beside the claim.

**Composed headline.** The displayed title is not a manuscript field. It is
``title_stem`` plus a qualifier computed from the derived reading scope, the
weakest evidence class, the ADR-0059 prior-art classification and the open
obligations tagged ``novelty`` or ``prior_art``. The composition is a ledger
block with resolving record references, so ADR-0036's byte-exact closure covers
the one string that used to sit outside it, and ``verify_headline_closure``
recomputes it from the records and refuses a document whose headline the ledger
does not account for.

**No clock, no randomness, no environment.** The document hash is a function of
the manuscript alone, so it is stable across calls and across processes.

The template carries zero manuscript data, which is what makes its hash a
meaningful constant. One consequence is worth stating: the document cannot
contain its own hash, so ``document_hash`` lives in ``MANIFEST.json`` and the
in-document provenance appendix carries the manuscript and template hashes only.
"""

